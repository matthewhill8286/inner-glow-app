#!/usr/bin/env node
/**
 * Records the sleep voice guidance in data/narration-scripts.json with OpenAI text-to-speech and
 * writes data/narration.ts, which maps each practice to its timed cues and their audio files.
 *
 *   node scripts/generate-narration.cjs
 *
 * Reads EXPO_PUBLIC_OPENAI_API_KEY (or OPENAI_API_KEY) from the environment or .env.local. A cue's
 * file name carries a hash of its text, so only new or changed lines are recorded again.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');
const scripts = JSON.parse(fs.readFileSync(path.join(root, 'data/narration-scripts.json'), 'utf8'));
const outDir = path.join(root, 'assets/narration');

function apiKey() {
  if (process.env.OPENAI_API_KEY) return process.env.OPENAI_API_KEY;
  if (process.env.EXPO_PUBLIC_OPENAI_API_KEY) return process.env.EXPO_PUBLIC_OPENAI_API_KEY;
  const env = fs.readFileSync(path.join(root, '.env.local'), 'utf8');
  const m = env.match(/^EXPO_PUBLIC_OPENAI_API_KEY=(.+)$/m);
  if (!m) throw new Error('No OpenAI API key in the environment or .env.local');
  return m[1].trim().replace(/^["']|["']$/g, '');
}

const VOICE = 'sage';
const INSTRUCTIONS = {
  en: 'Speak in English as a calm, warm sleep guide. Speak slowly and softly, close to a whisper but clear, with gentle pauses at commas and ellipses. Never sound cheerful or energetic.',
  el: 'Speak in Greek (Ελληνικά) with a natural Greek accent, as a calm, warm sleep guide. Speak slowly and softly, close to a whisper but clear, with gentle pauses at commas and ellipses. Never sound cheerful or energetic.',
};

async function record(lang, text, file) {
  const res = await fetch('https://api.openai.com/v1/audio/speech', {
    method: 'POST',
    headers: { Authorization: `Bearer ${apiKey()}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: 'gpt-4o-mini-tts',
      voice: VOICE,
      input: text,
      instructions: INSTRUCTIONS[lang],
      response_format: 'wav',
    }),
  });
  if (!res.ok) throw new Error(`TTS ${res.status}: ${(await res.text()).slice(0, 200)}`);
  const wav = file.replace(/\.mp3$/, '.wav');
  fs.writeFileSync(wav, Buffer.from(await res.arrayBuffer()));
  // Small mono files: a short fade in and out, quiet leading silence trimmed.
  execFileSync('ffmpeg', [
    '-y', '-loglevel', 'error', '-i', wav,
    '-af', 'silenceremove=start_periods=1:start_threshold=-50dB,afade=t=in:d=0.05,apad=pad_dur=0.3',
    '-ac', '1', '-ar', '24000', '-b:a', '48k', file,
  ]);
  fs.unlinkSync(wav);
}

function seconds(file) {
  const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]);
  return Math.round(Number(String(out).trim()) * 10) / 10;
}

(async () => {
  const keep = new Set();
  const lines = [];
  for (const lang of Object.keys(scripts).filter((k) => !k.startsWith('_'))) {
    fs.mkdirSync(path.join(outDir, lang), { recursive: true });
    lines.push(`  ${lang}: {`);
    for (const [practice, cues] of Object.entries(scripts[lang])) {
      lines.push(`    '${practice}': [`);
      for (const cue of cues) {
        const hash = crypto.createHash('sha1').update(`${VOICE}|${cue.text}`).digest('hex').slice(0, 8);
        const name = `${practice}-${cue.phase ?? cue.at}-${hash}.mp3`;
        const file = path.join(outDir, lang, name);
        keep.add(path.join(lang, name));
        if (!fs.existsSync(file)) {
          process.stdout.write(`recording ${lang}/${name}\n`);
          await record(lang, cue.text, file);
        }
        const when = cue.phase ? `phase: '${cue.phase}'` : `at: ${cue.at === 'end' ? "'end'" : cue.at}`;
        lines.push(
          `      { ${when}, seconds: ${seconds(file)}, file: require('@/assets/narration/${lang}/${name}') },`,
        );
      }
      lines.push('    ],');
    }
    lines.push('  },');
  }
  // Files for lines that changed or went away.
  for (const lang of fs.readdirSync(outDir)) {
    for (const f of fs.readdirSync(path.join(outDir, lang))) {
      if (!keep.has(path.join(lang, f))) fs.unlinkSync(path.join(outDir, lang, f));
    }
  }
  const ts = `/* Generated by scripts/generate-narration.cjs from data/narration-scripts.json. Do not edit. */
import type { NarrationScripts } from '@/lib/narration';

export const NARRATION: NarrationScripts = {
${lines.join('\n')}
};
`;
  fs.writeFileSync(path.join(root, 'data/narration.ts'), ts);
  process.stdout.write(`wrote data/narration.ts (${keep.size} cues)\n`);
})().catch((e) => {
  process.stderr.write(`${e.message}\n`);
  process.exit(1);
});
